package main

import "testing"

func TestFileDirectiveFindings_ForbiddenSource_Reported(t *testing.T) {
	for _, tt := range []struct {
		name, src, rule string
		line            int
	}{
		{"bare", "package x\n//nolint\n", "SEC-A1", 2},
		{"bare_reason", "package x\n//nolint // explanation\n", "SEC-A1", 2},
		{"depguard", "package x\n//nolint:depguard\n", "SEC-A1", 2},
		{"forbidigo", "package x\n/*nolint:forbidigo*/\n", "SEC-A1", 2},
		{"list_space", "package x\n//nolint:errcheck, depguard\n", "SEC-A1", 2},
		{"case", "package x\n//NoLint:DePgUaRd\n", "SEC-A1", 2},
		{"spaced", "package x\n// nolint:depguard\n", "SEC-A1", 2},
		{"slashes", "package x\n///nolint:depguard\n", "SEC-A1", 2},
		{"alligator", "package x\n//nolint:alligator\n", "SEC-A1", 2},
		{"cr", "package x\n//no\rlint:depguard\n", "SEC-A1", 2},
		{"permit", "package x\n//permit:x\n", "SEC-A2", 2},
		{"permit_space", "package x\n//  permit:x\n", "SEC-A2", 2},
		{"permit_label", "package x\nfunc f() { L://permit:x\n goto L }\n", "SEC-A2", 2},
		{"generated", "// Code generated by test. DO NOT EDIT.\npackage x\n", "GEN-MARKER", 1},
		{"generated_cr", "// Code gene\rrated by test. DO NOT EDIT.\npackage x\n", "GEN-MARKER", 1},
		{"generated_block", "/*\n// Code generated by test. DO NOT EDIT.\n*/\npackage x\n", "GEN-MARKER", 1},
		{"generated_indent", "  // Code generated by test. DO NOT EDIT.\npackage x\n", "GEN-MARKER", 1},
		{"line", "package x\n//line redirected.go:900\nvar x int\n", "LINE-DIRECTIVE", 2},
		{"line_block", "package x\n/*line redirected.go:900*/var x int\n", "LINE-DIRECTIVE", 2},
		{"linkname", "package x\n//go:linkname x time.now\n", "LINKNAME", 2},
		{"cgo", "package x\nimport \"C\"\n", "NON-GO-SOURCE", 2},
		{"import_escaped", "package x\nimport _ \"database/\\x73ql\"\n", "CANON-IMPORT", 2},
		{"import_raw", "package x\nimport _ `io/ioutil`\n", "CANON-IMPORT", 2},
		{"cgo_escaped", "package x\nimport \"\\x43\"\n", "CANON-IMPORT", 2},
		{"cgo_raw", "package x\nimport `C`\n", "CANON-IMPORT", 2},
	} {
		t.Run(tt.name, func(t *testing.T) {
			findings, err := fileDirectiveFindings("x.go", []byte(tt.src))
			if err != nil {
				t.Fatal(err)
			}
			if len(findings) != 1 {
				t.Fatalf("findings=%+v; want one", findings)
			}
			got := findings[0]
			if got.path != "x.go" || got.line != tt.line || got.rule != tt.rule {
				t.Fatalf("finding=%+v; want x.go:%d: %s", got, tt.line, tt.rule)
			}
		})
	}
}

func TestFileDirectiveFindings_InertText_Clean(t *testing.T) {
	for _, tt := range []struct{ name, src string }{
		{"other_linter", "package x\n//nolint" + ":gosec // explanation\n"},
		{"reason_names", "package x\n//nolint:errcheck // depguard forbidigo\n"},
		{"reason_comma", "package x\n//nolint:errcheck // reason,depguard\n"},
		{"string_url", "package x\nvar x = \"https://nolint:depguard\"\n"},
		{"prose_url", "package x\n// See https://permit:x for details.\n"},
		{"marker_after", "package x\n// Code generated by test. DO NOT EDIT.\n"},
		{"marker_string", "package x\nvar x = `// Code generated by test. DO NOT EDIT.`\n"},
		{"marker_prose", "// This says Code generated by test. DO NOT EDIT.\npackage x\n"},
		{"bom", "\ufeffpackage x\n"},
		{"nolintlint", "package x\n//nolintlint is a linter\n"},
		{"build_tag", "//go:build !windows\n\npackage x\n"},
		{"plain_imports", "package x\nimport (\n\"fmt\"\n_ \"net/http\"\n)\n"},
	} {
		t.Run(tt.name, func(t *testing.T) {
			findings, err := fileDirectiveFindings("x.go", []byte(tt.src))
			if err != nil {
				t.Fatal(err)
			}
			if len(findings) != 0 {
				t.Fatalf("findings=%+v; want none", findings)
			}
		})
	}
}

func TestFileDirectiveFindings_Unparsable_Errors(t *testing.T) {
	if _, err := fileDirectiveFindings("x.go", []byte("package x\nfunc (\n")); err == nil {
		t.Fatal("unparseable source: want error")
	}
	if _, err := directiveFindings(t.TempDir(), []string{"missing.go"}); err == nil {
		t.Fatal("unreadable source: want error")
	}
}
